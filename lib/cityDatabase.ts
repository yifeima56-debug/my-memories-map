export function searchLocalDatabase(query: string) {
  const normalizedQuery = query.toLowerCase().trim()

  // 精确匹配
  if (CITY_DATABASE[normalizedQuery as keyof typeof CITY_DATABASE]) {
    return [CITY_DATABASE[normalizedQuery as keyof typeof CITY_DATABASE]]
  }

  // 模糊匹配
  const matches = Object.entries(CITY_DATABASE)
    .filter(([key, value]) =>
      key.toLowerCase().includes(normalizedQuery) ||
      value.displayName.toLowerCase().includes(normalizedQuery)
    )
    .slice(0, 5)
    .map(([, value]) => value)

  return matches
}